package jobs

import (
	"slices"
	"testing"
	"time"

	"github.com/darkraise/darkpanel/internal/core"
)

// TestList lists Darkpanel jobs with their runs, the host's other timers and
// its cron entries, read-only, and shows command text to admins only.
func TestList(t *testing.T) {
	r := newRig(t)
	r.apply("jobs.job.create", backupInput)
	r.units.timers = []core.TimerInfo{
		{Name: "darkpanel-job-backup.timer", Unit: "darkpanel-job-backup.service", ActiveState: "active",
			Next: time.Date(2026, 11, 27, 3, 0, 0, 0, time.UTC), Last: time.Date(2026, 11, 26, 3, 0, 0, 0, time.UTC)},
		{Name: "apt-daily.timer", Unit: "apt-daily.service", ActiveState: "active", FragmentPath: "/usr/lib/systemd/system/apt-daily.timer",
			Next: time.Date(2026, 11, 27, 6, 0, 0, 0, time.UTC)},
	}
	r.units.runs["darkpanel-job-backup.service"] = core.ServiceRun{ActiveState: "inactive",
		Started: time.Date(2026, 11, 26, 3, 0, 4, 0, time.UTC), Result: "exit-code", ExitStatus: 2}
	r.files[systemCrontab] = "SHELL=/bin/sh\n# m h dom mon dow user command\n17 *\t* * *\troot    cd / && run-parts --report /etc/cron.hourly\n"
	r.files["/etc/cron.d/certbot"] = "PATH=/usr/bin\n0 */12 * * * root test -x /usr/bin/certbot && certbot -q renew\n@reboot root /usr/local/bin/warm\n"
	r.files["/var/spool/cron/crontabs/alice"] = "# DO NOT EDIT THIS FILE\nHOME = /home/alice/work dir with spaces\n*/5 * * * * /home/alice/bin/poll  --quiet\n"

	var admin JobList
	r.read(adminP, "jobs.job.list", `{}`, &admin)
	status := int32(2)
	want := Job{Slug: "backup", Description: "Nightly 100% backup", Schedule: "*-*-* 03:00:00", User: "alice", Command: "tar czf /tmp/x.tgz /etc",
		TimeoutSeconds: 3600, CatchUp: true, RandomDelaySeconds: 300, Enabled: true, NextRun: "2026-11-27T03:00:00Z",
		LastStart: "2026-11-26T03:00:04Z", LastResult: "exit-code", ExitStatus: &status}
	if len(admin.Jobs) != 1 || !jobEqual(admin.Jobs[0], want) {
		t.Errorf("jobs %+v, want %+v", admin.Jobs, want)
	}
	if want := []OtherTimer{{Name: "apt-daily.timer", Unit: "apt-daily.service", Source: "/usr/lib/systemd/system/apt-daily.timer",
		NextRun: "2026-11-27T06:00:00Z"}}; !slices.Equal(admin.Timers, want) {
		t.Errorf("timers %+v, want %+v", admin.Timers, want)
	}
	wantCron := []CronEntry{
		{Source: systemCrontab, Schedule: "17 * * * *", User: "root", Command: "cd / && run-parts --report /etc/cron.hourly"},
		{Source: "/etc/cron.d/certbot", Schedule: "0 */12 * * *", User: "root", Command: "test -x /usr/bin/certbot && certbot -q renew"},
		{Source: "/etc/cron.d/certbot", Schedule: "@reboot", User: "root", Command: "/usr/local/bin/warm"},
		{Source: "/var/spool/cron/crontabs/alice", Schedule: "*/5 * * * *", User: "alice", Command: "/home/alice/bin/poll  --quiet"},
	}
	if !slices.Equal(admin.Cron, wantCron) {
		t.Errorf("cron\n %+v\nwant\n %+v", admin.Cron, wantCron)
	}

	var viewer JobList
	r.read(viewerP, "jobs.job.list", `{}`, &viewer)
	if len(viewer.Jobs) != 1 || viewer.Jobs[0].Command != "" || viewer.Jobs[0].Schedule != want.Schedule {
		t.Errorf("a viewer's jobs %+v: want the job without its command", viewer.Jobs)
	}
	for _, e := range viewer.Cron {
		if e.Command != "" {
			t.Errorf("a viewer sees the cron command %q of %s", e.Command, e.Source)
		}
	}
	if len(viewer.Cron) != len(wantCron) {
		t.Errorf("a viewer sees %d cron entries, want %d", len(viewer.Cron), len(wantCron))
	}
}

func jobEqual(a, b Job) bool {
	if (a.ExitStatus == nil) != (b.ExitStatus == nil) || (a.ExitStatus != nil && *a.ExitStatus != *b.ExitStatus) {
		return false
	}
	a.ExitStatus, b.ExitStatus = nil, nil
	return a == b
}
