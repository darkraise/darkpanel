func TestM3xDockRoutes(t *testing.T) {
	rules := []model.Rule{
		{ID: "01J00000000000000000000001", Action: model.ActionAllow, Direction: model.DirRoute, Proto: model.ProtoTCP, From: model.Any, To: "172.17.0.2", ToPort: "14000",
			OutIface: "docker0", Family: model.FamilyV4, Comment: "ctr 01J00000000000000000000009", Origin: model.OriginDarkpanel},
		{ID: "manual-0123456789abcdef", Action: model.ActionAllow, Direction: model.DirRoute, Proto: model.ProtoTCP, From: "192.0.2.0/24", To: model.Any, ToPort: "9099",
			Family: model.FamilyV4, Origin: model.OriginManual},
		{ID: "manual-aaaaaaaaaaaaaaaa", Action: model.ActionAllow, Direction: model.DirIn, Proto: model.ProtoTCP, From: model.Any, To: model.Any, ToPort: "22", Family: model.FamilyBoth, Origin: model.OriginManual},
	}
	got := m3dxDockRoutes(rules)
	if len(got) != 2 {
		t.Fatalf("m3dxDockRoutes = %q, want the two route rules and not the incoming one", got)
	}
	if !slices.IsSorted(got) {
		t.Errorf("m3dxDockRoutes is not sorted: %q", got)
	}
	swapped := []model.Rule{rules[2], rules[1], rules[0]}
	if again := m3dxDockRoutes(swapped); !slices.Equal(got, again) {
		t.Errorf("m3dxDockRoutes depends on the order of the rules:\n%q\n%q", got, again)
	}
	changed := slices.Clone(rules)
	changed[0].Comment = "ctr 01J0000000000000000000000A"
	if again := m3dxDockRoutes(changed); slices.Equal(got, again) {
		t.Error("m3dxDockRoutes ignores a rule's tag")
	}
	dropped := rules[1:]
	if again := m3dxDockRoutes(dropped); slices.Equal(got, again) {
		t.Error("m3dxDockRoutes ignores a missing rule")
	}
}

// TestM3xDockStatusJSON pins the field names of m3dDockStatus to the JSON
// of the firewall.docker resource (Contracts: DockerStatus).
func TestM3xDockStatusJSON(t *testing.T) {
	const doc = `{"available":true,"version":"29.9.1","driver":"iptables","dockerVariant":"nft","ufwVariant":"nft","rawProtection":true,"supported":true,
"enabled":true,"health":"broken","issues":[{"level":"broken","reason":"foreign rule"}],"foreignRules":["-s 192.0.2.78/32 -j DROP"],
"foreignForwards":[{"origDestination":"198.18.0.11","origPort":9100,"destination":"192.0.2.50","proto":"tcp","port":9100}],
"manualRoutes":["route allow 9099/tcp"],
"networks":[{"name":"bridge","id":"abcdef0123456789","bridge":"docker0","subnets":["172.17.0.0/16"],"protected":true}],
"settings":{"privateSources":["10.0.0.0/8"],"forwardExemptions":[{"inInterface":"dpinet","origDestination":"198.18.0.11","destination":"192.0.2.50","proto":"tcp"}]},
"rules":[{"id":"01J00000000000000000000001","binding":{"selector":"web","hostPort":8080,"proto":"tcp"},"kind":"allow","from":"198.18.0.20/32"}],
"bindings":[{"binding":{"selector":"web","hostPort":8080,"proto":"tcp"},"id":"0123456789ab","containers":["web"],"containerPort":80,"allowed":["198.18.0.20/32"],"denied":[],"proxied":["v6"],"privateReach":["10.0.0.0/8"]}]}`
	var st m3dDockStatus
	if err := json.Unmarshal([]byte(doc), &st); err != nil {
		t.Fatal(err)
	}
	switch {
	case !st.Available || st.Version != "29.9.1" || st.Driver != "iptables" || st.DockerVariant != "nft" || st.UFWVariant != "nft" || !st.RawProtection || !st.Supported:
		t.Errorf("detection fields: %+v", st)
	case !st.Enabled || st.Health != "broken" || len(st.Issues) != 1 || st.Issues[0].Level != "broken" || st.Issues[0].Reason != "foreign rule":
		t.Errorf("health fields: %+v", st)
	case !slices.Equal(st.ForeignRules, []string{"-s 192.0.2.78/32 -j DROP"}) || len(st.ManualRoutes) != 1:
		t.Errorf("foreign and manual rules: %+v", st)
	case len(st.ForeignForwards) != 1 || st.ForeignForwards[0] != (m3dDockExemption{OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.50", Proto: "tcp", Port: 9100}):
		t.Errorf("foreign forwards: %+v", st.ForeignForwards)
	case len(st.Networks) != 1 || st.Networks[0].Bridge != "docker0" || !slices.Equal(st.Networks[0].Subnets, []string{"172.17.0.0/16"}) || !st.Networks[0].Protected:
		t.Errorf("networks: %+v", st.Networks)
	case !slices.Equal(st.Settings.PrivateSources, []string{"10.0.0.0/8"}) || len(st.Settings.ForwardExemptions) != 1 || st.Settings.ForwardExemptions[0].InInterface != "dpinet":
		t.Errorf("settings: %+v", st.Settings)
	case len(st.Rules) != 1 || st.Rules[0].Binding.HostPort != 8080 || st.Rules[0].Kind != "allow" || st.Rules[0].From != "198.18.0.20/32":
		t.Errorf("rules: %+v", st.Rules)
	case len(st.Bindings) != 1 || st.Bindings[0].ID != "0123456789ab" || st.Bindings[0].ContainerPort != 80 || !slices.Equal(st.Bindings[0].Proxied, []string{"v6"}) ||
		!slices.Equal(st.Bindings[0].PrivateReach, []string{"10.0.0.0/8"}):
		t.Errorf("bindings: %+v", st.Bindings)
	}
}
