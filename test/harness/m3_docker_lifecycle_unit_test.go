func TestM3xDockDetected(t *testing.T) {
	ok := m3dDockStatus{Available: true, Supported: true, Version: "29.9.1", Driver: "iptables", DockerVariant: "nft", UFWVariant: "nft",
		RawProtection: true, Health: "off", Networks: []m3dDockNetwork{{Name: "bridge", Bridge: "docker0", Subnets: []string{"172.17.0.0/16"}}}}
	if err := m3dxDockDetected(ok); err != nil {
		t.Fatalf("a supported Docker host: %v", err)
	}
	for _, tc := range []struct {
		name string
		edit func(*m3dDockStatus)
		want string
	}{
		{"unavailable", func(s *m3dDockStatus) { s.Available, s.Reason = false, "no socket" }, "unavailable: no socket"},
		{"unsupported", func(s *m3dDockStatus) { s.Supported, s.Unsupported = false, []string{"raw protection is not loaded"} }, "raw protection is not loaded"},
		{"old docker", func(s *m3dDockStatus) { s.Version = "27.5.1" }, "27.5.1"},
		{"nftables driver", func(s *m3dDockStatus) { s.Driver = "nftables" }, "nftables"},
		{"no raw protection", func(s *m3dDockStatus) { s.RawProtection = false }, "raw"},
		{"variants differ", func(s *m3dDockStatus) { s.DockerVariant = "legacy" }, "legacy"},
		{"no variant", func(s *m3dDockStatus) { s.DockerVariant, s.UFWVariant = "", "" }, "variant"},
		{"already enabled", func(s *m3dDockStatus) { s.Enabled, s.Health = true, "ok" }, "enabled"},
		{"no default bridge", func(s *m3dDockStatus) { s.Networks = nil }, "bridge"},
	} {
		st := ok
		tc.edit(&st)
		if err := m3dxDockDetected(st); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: %v, want an error naming %q", tc.name, err, tc.want)
		}
	}
}

func TestM3xDockHealth(t *testing.T) {
	check := m3dxDockHealth("ok")
	if err := check(m3dDockStatus{Enabled: true, Health: "ok"}); err != nil {
		t.Errorf("an enabled ok integration: %v", err)
	}
	if err := check(m3dDockStatus{Enabled: false, Health: "ok"}); err == nil {
		t.Error("a disabled integration passed")
	}
	err := check(m3dDockStatus{Enabled: true, Health: "broken", Issues: []m3dDockIssue{{Level: "broken", Reason: "foreign rule -s 192.0.2.78/32 -j DROP"}}})
	if err == nil || !strings.Contains(err.Error(), "192.0.2.78") || !strings.Contains(err.Error(), "broken") {
		t.Errorf("a broken integration: %v, want an error naming the health and its issue", err)
	}
}

func TestM3xDockSave(t *testing.T) {
	if got, want := m3dxDockChains(m3dxDockSaveBlock), []string{"darkpanel-docker-bindings", "darkpanel-docker-deny", "dp-b-0123456789ab"}; !slices.Equal(got, want) {
		t.Errorf("m3dxDockChains = %q, want %q", got, want)
	}
	if got := m3dxDockChains(m3dxDockSaveClean); len(got) != 0 {
		t.Errorf("m3dxDockChains of a clean save = %q", got)
	}
	rules := m3dxDockRulesOf(m3dxDockSaveBlock, "DOCKER-USER")
	if len(rules) != 7 || rules[0] != "-m conntrack --ctstate RELATED,ESTABLISHED -j RETURN" || rules[6] != "-j RETURN" {
		t.Errorf("m3dxDockRulesOf(DOCKER-USER) = %q", rules)
	}
	if got := m3dxDockRulesOf(m3dxDockSaveBlock, "DOCKER"); len(got) != 0 {
		t.Errorf("m3dxDockRulesOf(DOCKER) = %q, want none: DOCKER-USER's rules must not leak into a chain that is its prefix", got)
	}
	if got := m3dxDockRulesOf(m3dxDockSaveBlock, "darkpanel-docker-deny"); len(got) != 2 {
		t.Errorf("m3dxDockRulesOf(darkpanel-docker-deny) = %q", got)
	}
}

func TestM3xDockCleaned(t *testing.T) {
	const foreign = "-s 192.0.2.77/32 -j DROP"
	withForeign := strings.Replace(m3dxDockSaveClean, "-A DOCKER-USER -j RETURN", "-A DOCKER-USER "+foreign+"\n-A DOCKER-USER -j RETURN", 1)
	noRule := strings.Replace(m3dxDockSaveClean, "-A DOCKER-USER -j RETURN\n", "", 1)
	for _, tc := range []struct {
		name       string
		save       string
		foreign    []string
		wantReturn bool
		want       string // "" accepts
	}{
		{"clean", m3dxDockSaveClean, nil, true, ""},
		{"foreign preserved", withForeign, []string{foreign}, true, ""},
		{"chains left", m3dxDockSaveBlock, nil, true, "darkpanel-docker-bindings"},
		{"unexpected foreign", withForeign, nil, true, "192.0.2.77"},
		{"foreign lost", m3dxDockSaveClean, []string{foreign}, true, "192.0.2.77"},
		{"no return rule", noRule, nil, true, "-j RETURN"},
		{"no return rule is fine when not wanted", noRule, nil, false, ""},
	} {
		err := m3dxDockCleaned(tc.save, tc.foreign, tc.wantReturn)
		switch {
		case tc.want == "" && err != nil:
			t.Errorf("%s: %v, want nil", tc.name, err)
		case tc.want != "" && (err == nil || !strings.Contains(err.Error(), tc.want)):
			t.Errorf("%s: %v, want an error naming %q", tc.name, err, tc.want)
		}
	}
}

func TestM3xDockBlockLoaded(t *testing.T) {
	if err := m3dxDockBlockLoaded(m3dxDockSaveBlock); err != nil {
		t.Errorf("a loaded block: %v", err)
	}
	if err := m3dxDockBlockLoaded(m3dxDockSaveClean); err == nil || !strings.Contains(err.Error(), "darkpanel-docker-bindings") {
		t.Errorf("a clean save: %v, want an error naming the missing chain", err)
	}
	noGate := strings.Replace(m3dxDockSaveBlock, "-A DOCKER-USER -m conntrack --ctstate DNAT -j darkpanel-docker-bindings\n", "", 1)
	if err := m3dxDockBlockLoaded(noGate); err == nil || !strings.Contains(err.Error(), "DNAT") {
		t.Errorf("a block without its DNAT gate: %v, want an error naming it", err)
	}
	noDrop := strings.Replace(m3dxDockSaveBlock, "-A darkpanel-docker-deny -j DROP\n", "", 1)
	if err := m3dxDockBlockLoaded(noDrop); err == nil || !strings.Contains(err.Error(), "DROP") {
		t.Errorf("a block whose deny chain does not drop: %v, want an error naming DROP", err)
	}
}

func TestM3xDockExemptionLine(t *testing.T) {
	want := m3dDockExemption{InInterface: "dpinet", OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.50", Proto: "tcp", Port: 9100}
	if err := m3dxDockExemptionLine(m3dxDockSaveBlock, want); err != nil {
		t.Errorf("the exemption's line: %v", err)
	}
	for name, e := range map[string]m3dDockExemption{
		"other original port":    {InInterface: "dpinet", OrigDestination: "198.18.0.11", OrigPort: 9101, Destination: "192.0.2.50", Proto: "tcp", Port: 9100},
		"other destination":      {InInterface: "dpinet", OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.51", Proto: "tcp", Port: 9100},
		"other protocol":         {InInterface: "dpinet", OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.50", Proto: "udp", Port: 9100},
		"other interface":        {InInterface: "dppriv", OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.50", Proto: "tcp", Port: 9100},
		"other host address":     {InInterface: "dpinet", OrigDestination: "198.18.0.12", OrigPort: 9100, Destination: "192.0.2.50", Proto: "tcp", Port: 9100},
		"the destination's port": {InInterface: "dpinet", OrigDestination: "198.18.0.11", OrigPort: 9100, Destination: "192.0.2.50", Proto: "tcp", Port: 9200},
	} {
		if err := m3dxDockExemptionLine(m3dxDockSaveBlock, e); err == nil {
			t.Errorf("%s: a line that is not the exemption's was accepted", name)
		}
	}
	notReturn := strings.Replace(m3dxDockSaveBlock, "--dport 9100 -j RETURN", "--dport 9100 -j ACCEPT", 1)
	if err := m3dxDockExemptionLine(notReturn, want); err == nil {
		t.Error("an exemption line that does not return was accepted")
	}
	v6 := "-A DOCKER-USER -d fd00:3d::50/128 -p tcp -m conntrack --ctstate DNAT --ctorigdst 2001:db8:d0::11 -j RETURN\n"
	if err := m3dxDockExemptionLine(v6, m3dDockExemption{OrigDestination: "2001:db8:d0::11", Destination: "fd00:3d::50", Proto: "tcp"}); err != nil {
		t.Errorf("an IPv6 exemption without ports: %v", err)
	}
}

